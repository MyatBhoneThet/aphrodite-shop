const normalize = (value: string) => value.replaceAll("_", " ").replace(/\s+/g, " ").trim().toLowerCase();
const dictionary = new Map(Object.entries({
  ...Object.fromEntries(Object.values(translations).map(pair => [pair.en, pair.my])),
  ...storefrontBurmese,
  ...adminBurmese,
}).map(([en, my]) => [normalize(en), my]));

/** Translate interface copy only. Never use for customer-entered content or stored identifiers. */
export function translateAdminText(language: Language, value: string): string {
  if (language === "en") return value;
  const translated = dictionary.get(normalize(value));
  if (translated) return translated;
  const count = value.match(/^(\d+) (pending|out of stock|waiting)$/);
  if (count) return `${translateAdminText(language, count[2])} ${count[1]} ခု`;
  return value;
}
